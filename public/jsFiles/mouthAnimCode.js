//update the rate at which the mouth speaks
function updateSpeakSpeed() {
    let selectedSpeed = document.getElementById("speeds").value;
    
    switch(selectedSpeed) {
        case 'verySlow':
            timeForEachFrame = 180;
            speechRate = 0.1;
            break;
        case 'slow':
            timeForEachFrame = 70;
            speechRate = 0.4;
            break;
        case 'medium':
            timeForEachFrame = 55;
            speechRate = 1;
            break;
        case 'fast':
            timeForEachFrame = 35;
            speechRate = 2;
            break;
        default:
            timeForEachFrame = 55;
            speechRate = 1;
            break;
    }

    console.log(timeForEachFrame+' & '+speechRate);
}

